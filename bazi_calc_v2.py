BAN_HE_GROUPS = [
    {"申", "子", "辰"}, {"巳", "酉", "丑"},
    {"寅", "午", "戌"}, {"亥", "卯", "未"}
]

def check_ban_he(z1, z2):
    for group in BAN_HE_GROUPS:
        if z1 in group and z2 in group and z1 != z2: return True
    return False

def check_xing_detail(z1, z2):
    if z1 == z2 and z1 in ["辰", "午", "酉", "亥"]: return "自刑"
    if (z1 == "子" and z2 == "卯") or (z1 == "卯" and z2 == "子"): return "無禮之刑"
    if (z1 == "寅" and z2 == "巳") or (z1 == "巳" and z2 == "申") or (z1 == "申" and z2 == "寅"): return "無恩之刑"
    if (z1 == "丑" and z2 == "戌") or (z1 == "戌" and z2 == "未") or (z1 == "未" and z2 == "丑"): return "恃勢之刑"
    return None

def analyze_pair_logic(main_zhi, target_zhi, detailed_xing=False):
    """
    純邏輯函數，回傳關係列表
    """
    relations = []
    # 順序：六合 -> 半合 -> 沖 -> 刑 -> 害 -> 破 -> 無特殊
    if LIU_HE.get(main_zhi) == target_zhi: 
        relations.append({"name": "六合", "type": "good"})
    
    if check_ban_he(main_zhi, target_zhi): 
        relations.append({"name": "半合", "type": "good"})
        
    if LIU_CHONG.get(main_zhi) == target_zhi: 
        relations.append({"name": "沖", "type": "bad"})
        
    xing_type = check_xing_detail(main_zhi, target_zhi)
    if xing_type:
        name = f"刑 ({xing_type})" if detailed_xing else "刑"
        relations.append({"name": name, "type": "bad"})
        
    if LIU_HAI.get(main_zhi) == target_zhi: 
        relations.append({"name": "害", "type": "warn"})
        
    if XIANG_PO.get(main_zhi) == target_zhi: 
        relations.append({"name": "破", "type": "warn"})
        
    if not relations: 
        relations.append({"name": "無特殊關係", "type": "normal"})
        
    return relations

